"""Rebuild static/primer.css from one pinned Primer Primitives release.

Fetch the release's three files into a folder, then point this at it:

    mkdir -p /tmp/primer && cd /tmp/primer && for f in dist/css/functional/themes/light.css \
        dist/css/functional/themes/dark.css LICENSE; do mkdir -p "$(dirname "$f")"; \
        curl -sSfL -o "$f" "https://unpkg.com/@primer/primitives@11.10.0/$f"; done
    uv run python scripts/vendor_primer.py /tmp/primer

Primer ships its themes keyed on data-color-mode attributes; this panel follows the reader's
system setting unless they chose a theme in its header, so the subset is rewritten under :root,
prefers-color-scheme and the page's own data-theme attribute. Run it
to refresh the tokens; never edit primer.css by hand. Every fetched file is checked against the
sha256 recorded below, and every value against a plain colour pattern, so a changed or
hostile upstream file stops the run instead of reaching the served stylesheet.
"""

import hashlib
import re
import sys
from pathlib import Path

VERSION = "11.10.0"
OUT = Path(__file__).resolve().parent.parent / "src/knotview/panel/static"
WANTED = (
    "fgColor-default",
    "fgColor-muted",
    "fgColor-onEmphasis",
    "fgColor-accent",
    "fgColor-success",
    "fgColor-attention",
    "fgColor-severe",
    "fgColor-danger",
    "fgColor-done",
    "bgColor-default",
    "bgColor-muted",
    "bgColor-inset",
    "bgColor-emphasis",
    "bgColor-accent-muted",
    "bgColor-success-muted",
    "bgColor-attention-muted",
    "bgColor-severe-muted",
    "bgColor-danger-muted",
    "bgColor-done-muted",
    "bgColor-neutral-muted",
    "borderColor-default",
    "borderColor-muted",
    "borderColor-emphasis",
    "borderColor-attention-emphasis",
)
# The sha256 of each file at VERSION, so a file that is not the pinned release stops the run.
PINNED: dict[str, str] = {
    "dist/css/functional/themes/light.css": (
        "86468bdfa1761f189d7bed7c1a13c6183f67ec132d689dacc63acc9eec986496"
    ),
    "dist/css/functional/themes/dark.css": (
        "d70cf0d4f3b2b1056030b40fcf1cd65b1d74d07dbbec002ad300e08266188d89"
    ),
    "LICENSE": "e63582a78dddebe610b6cb59f0e7f5f761c1bb6a1c9551443beddc64fe525c3a",
}
SAFE = re.compile(r"^[#\w\s(),.%-]+$")


def fetched(folder: Path, path: str) -> str:
    """One file of the pinned release, refused if its hash differs from the pinned one."""
    body = (folder / path).read_bytes()
    digest = hashlib.sha256(body).hexdigest()
    if PINNED[path] != digest:
        sys.exit(f"{path} is not the pinned {VERSION} file: sha256 {digest}")
    return body.decode()


def picked(css: str) -> list[str]:
    """The wanted declarations, in WANTED order; a missing or unsafe one stops the run."""
    found = dict(re.findall(r"--([\w-]+):\s*([^;]+);", css))
    missing = [one for one in WANTED if one not in found]
    if missing:
        sys.exit(f"not in primer {VERSION}: {', '.join(missing)}")
    unsafe = [one for one in WANTED if not SAFE.match(found[one].strip())]
    if unsafe:
        sys.exit(f"not a plain colour value: {', '.join(unsafe)}")
    return [f"  --{one}: {found[one].strip()};" for one in WANTED]


def main() -> None:
    """Write primer.css and the license beside it, from the folder named on the command line."""
    if len(sys.argv) != 2:
        sys.exit("usage: vendor_primer.py <folder holding the release's files>")
    folder = Path(sys.argv[1])
    light = picked(fetched(folder, "dist/css/functional/themes/light.css"))
    dark = picked(fetched(folder, "dist/css/functional/themes/dark.css"))
    header = (
        f"/* Generated by scripts/vendor_primer.py from @primer/primitives@{VERSION} (MIT, see\n"
        " * PRIMER-LICENSE). A subset: light by default, dark when the system asks for it unless\n"
        " * the reader chose light, and dark whenever the reader chose dark. Do not edit. */\n"
    )
    body = (
        ":root {\n"
        + "\n".join(light)
        + "\n}\n\n@media (prefers-color-scheme: dark) {\n"
        + '  :root:not([data-theme="light"]) {\n'
        + "\n".join("  " + line for line in dark)
        + "\n  }\n}\n\n"
        + ':root[data-theme="dark"] {\n'
        + "\n".join(dark)
        + "\n}\n"
    )
    (OUT / "primer.css").write_text(header + body, encoding="utf-8")
    (OUT / "PRIMER-LICENSE").write_text(fetched(folder, "LICENSE"), encoding="utf-8")


if __name__ == "__main__":
    main()
